function m=cnse_metrics(r)
c=r.c;w=c.warmup;stop=c.duration;a=r.results;
use=a(:,3)>=w & a(:,3)<stop & a(:,1)<=stop;
f=r.frames;f=f(f(:,2)>=w & f(:,2)<stop,:);
p=r.tx;sel=p(:,1)>=w & p(:,1)<stop;
x=r.rx;rxsel=x(:,1)>=w & x(:,1)<stop;
m=struct('sequence_loss',mean(p(sel,10)),...
 'frame_loss',mean(isinf(f(:,4))),'on_time',mean(f(:,6)==1),...
 'late',mean(isfinite(f(:,4)) & f(:,4)>f(:,3)),...
 'jitter_ms',mean(x(rxsel,12)),...
 'latency_p50_ms',course.percentile(1000*(a(use,1)-a(use,3)),50),...
 'latency_p95_ms',course.percentile(1000*(a(use,1)-a(use,3)),95),...
 'aoi_ms',1000*course.aoi(a(:,1),a(:,3),w,stop));
end
